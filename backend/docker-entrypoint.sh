#!/bin/sh
# Запускается при старте контейнера backend:
# 1) применяет миграции, 2) создаёт тестового админа, 3) запускает сервер
set -e

echo "→ Применяем миграции Alembic..."
alembic upgrade head

echo "→ Создаём тестового администратора (если его ещё нет)..."
python -m scripts.seed_admin

echo "→ Запускаем: $*"
exec "$@"
